#!/usr/bin/env python3
"""Turns a DSLeaf .fnt file into a C source file with the font as an array, so it can be built into the program.

    python3 -I tools/fnt2c.py font6x12.fnt source/font_6x12.c

The C file starts with the copyright notice and the licence statement that the font's licence (SIL Open
Font License 1.1, see third_party/terminus/OFL.txt) asks every copy to carry. Edit NOTICE below for another font.
"""
import sys
from pathlib import Path

NOTICE = """/*
 * The 6x12 font built into DSLeaf (shown in the program as "Built-in 6x12").
 *
 * This is a Modified Version (converted to the DSLeaf .fnt format, glyphs U+0000 to U+00FF only) of the
 * Terminus Font, regular weight 6x12 (ter-u12n.bdf, Terminus Font 4.49.1):
 *
 *   Copyright (C) 2020 Dimitar Toshkov Zhekov,
 *   with Reserved Font Name "Terminus Font".
 *
 * This Font Software is licensed under the SIL Open Font License, Version 1.1. The full licence is in
 * third_party/terminus/OFL.txt and is also available with a FAQ at http://scripts.sil.org/OFL
 *
 * As the licence asks, this Modified Version does not use the Reserved Font Name as its name, and it is
 * distributed under the same licence. The rest of DSLeaf is under the MIT licence (see LICENSE); this file's
 * data is not: it is under the SIL Open Font License.
 *
 * Generated by tools/fnt2c.py from the output of tools/bdf2fnt.py. Do not edit the numbers by hand.
 */
"""

def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    data = Path(sys.argv[1]).read_bytes()
    lines = [NOTICE, '#include "font_builtin.h"\n', f'const unsigned char font_6x12_data[{len(data)}] = {{']
    for i in range(0, len(data), 16):
        lines.append("\t" + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines.append("};\n")
    lines.append(f"const unsigned long font_6x12_size = {len(data)};")
    Path(sys.argv[2]).write_text("\n".join(lines) + "\n")
    print(f"wrote {sys.argv[2]}: {len(data)} bytes")

main()
