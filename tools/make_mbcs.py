#!/usr/bin/env python3
"""Writes source/mbcs_tables.c: the tables for reading text files in the old double-byte encodings (decision 094):
GBK (GB2312 and its extension), Big5, Shift-JIS (Windows code page 932) and EUC-KR (the Windows code page 949).

    python3 -I tools/make_mbcs.py source/mbcs_tables.c

Each table maps a lead byte and a trail byte to a Unicode code point (0 for a pair that is not a character), made with
Python's codecs. Only code points of the Basic Multilingual Plane are used. The Windows-1251 table (Cyrillic) is here too.
"""
import sys

# name, python codec, lead bytes (ranges), trail bytes (range)
SPECS = [
    ("gbk", "gbk", [(0x81, 0xFE)], (0x40, 0xFE)),
    ("big5", "big5", [(0xA1, 0xF9)], (0x40, 0xFE)),
    ("sjis", "cp932", [(0x81, 0x9F), (0xE0, 0xFC)], (0x40, 0xFC)),
    ("euckr", "cp949", [(0x81, 0xFE)], (0x41, 0xFE)),
]

def decode(codec, lead, trail):
    try:
        s = bytes([lead, trail]).decode(codec)
    except UnicodeDecodeError:
        return 0
    if len(s) != 1 or ord(s) > 0xFFFF:
        return 0
    return ord(s)

def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    out = ['// Generated by tools/make_mbcs.py. Do not edit by hand.', '#include "mbcs.h"', '']
    for name, codec, leads, (t0, t1) in SPECS:
        rows = []
        for a, b in leads:
            for lead in range(a, b + 1):
                rows.append([decode(codec, lead, t) for t in range(t0, t1 + 1)])
        flat = [v for r in rows for v in r]
        used = sum(1 for v in flat if v)
        out.append("// %s: %d lead bytes, trail bytes 0x%02X to 0x%02X, %d characters" % (name, len(rows), t0, t1, used))
        out.append("const uint16_t mb_%s[%d] = {" % (name, len(flat)))
        for i in range(0, len(flat), 12):
            out.append("\t" + ", ".join("0x%04X" % v for v in flat[i:i + 12]) + ",")
        out.append("};\n")
    high = []
    for b in range(0x80, 0x100):
        try:
            high.append(ord(bytes([b]).decode("cp1251")))
        except UnicodeDecodeError:
            high.append(0xFFFD)
    out.append("const uint16_t cp1251_high[128] = {")
    for i in range(0, 128, 8):
        out.append("\t" + ", ".join("0x%04X" % v for v in high[i:i + 8]) + ",")
    out.append("};")
    open(sys.argv[1], "w").write("\n".join(out) + "\n")
    print("written")

main()
