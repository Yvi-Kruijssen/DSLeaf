#!/usr/bin/env python3
"""Writes source/font_6x12_ext.c: the Greek and Cyrillic glyphs (U+0370 to U+04FF) of Terminus 6x12, for the built-in
6x12 font (decision 091).

    python3 -I tools/bdf2ext.py ter-u12n.bdf source/font_6x12_ext.c

Only the glyphs the font has are written, in runs of consecutive code points. Each glyph is 12 bytes, one for each
row from the top, bit 0 the leftmost pixel (the same as the .fnt format). The file carries the same notice as
font_6x12.c: it is a Modified Version of Terminus Font under the SIL Open Font License.
"""
import sys

FIRST, LAST = 0x370, 0x4FF

NOTICE = """/*
 * The Greek and Cyrillic letters of the 6x12 font built into DSLeaf (shown in the program as "Built-in 6x12").
 *
 * This is a Modified Version (converted to a C array, glyphs U+0370 to U+04FF only) of the Terminus Font,
 * regular weight 6x12 (ter-u12n.bdf, Terminus Font 4.49.1):
 *
 *   Copyright (C) 2020 Dimitar Toshkov Zhekov,
 *   with Reserved Font Name "Terminus Font".
 *
 * This Font Software is licensed under the SIL Open Font License, Version 1.1. The full licence is in
 * third_party/terminus/OFL.txt and is also available with a FAQ at http://scripts.sil.org/OFL
 *
 * As the licence asks, this Modified Version does not use the Reserved Font Name as its name, and it is
 * distributed under the same licence. The rest of DSLeaf is under the MIT licence (see LICENSE); this file's
 * data is not: it is under the SIL Open Font License.
 *
 * Generated by tools/bdf2ext.py. Do not edit the numbers by hand.
 */
"""

def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    glyphs, enc, rows, in_bitmap, width = {}, None, [], False, 6
    for line in open(sys.argv[1], encoding="latin-1"):
        p = line.split()
        if not p:
            continue
        if p[0] == "ENCODING":
            enc = int(p[1])
        elif p[0] == "BITMAP":
            rows, in_bitmap = [], True
        elif p[0] == "ENDCHAR":
            in_bitmap = False
            glyphs[enc] = rows
        elif in_bitmap:
            rows.append(int(p[0], 16))
    present = [c for c in sorted(glyphs) if FIRST <= c <= LAST]
    runs = []
    for c in present:
        if runs and c == runs[-1][0] + runs[-1][1]:
            runs[-1][1] += 1
        else:
            runs.append([c, 1])
    data = bytearray()
    for c in present:
        r = glyphs[c]
        assert len(r) == 12, hex(c)
        for row in r:   # BDF: the leftmost pixel is the top bit of the byte; ours is bit 0
            data.append(sum(((row >> (7 - x)) & 1) << x for x in range(width)))
    out = [NOTICE, '#include "font_ext.h"\n']
    out.append("const FontRange font_ext_ranges[%d] = {" % len(runs))
    off = 0
    for first, count in runs:
        out.append("\t{ 0x%04X, %d, %d }," % (first, count, off))
        off += count
    out.append("};\n")
    out.append("const int font_ext_range_count = %d;\n" % len(runs))
    out.append("const unsigned char font_ext_rows[%d] = {" % len(data))
    for i in range(0, len(data), 12):
        out.append("\t" + ", ".join("0x%02x" % b for b in data[i:i + 12]) + ",")
    out.append("};")
    open(sys.argv[2], "w").write("\n".join(out) + "\n")
    print(len(present), "glyphs in", len(runs), "runs,", len(data), "bytes")

main()
