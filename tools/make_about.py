#!/usr/bin/env python3
"""Writes source/about_text.c, the text of the About screen (decisions 077 and 087), from LICENSE and
the licence files in third_party/. Run it again when either file changes:  python3 tools/make_about.py"""
import re, sys, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def paragraphs(path):
    text = open(os.path.join(root, path), encoding="utf-8").read().replace("\r", "")
    out, cur = [], []
    for line in text.split("\n"):
        if re.fullmatch(r"-{5,}", line.strip()):
            continue
        if line.strip() == "":
            if cur: out.append(" ".join(cur)); cur = []
        else:
            cur.append(line.strip())
    if cur: out.append(" ".join(cur))
    return out

def ascii_only(s):
    return (s.replace("’", "'").replace("‘", "'").replace("“", '"').replace("”", '"')
             .replace("–", "-").replace("—", "-").replace("©", "(c)"))

items = ["#DSLeaf \"  DSLEAF_VERSION  \"",
         "An e-reader for the Nintendo DS, DS Lite and Game Boy Macro.",
         "github.com/Yvi-Kruijssen/DSLeaf", "",
         "#Licence of DSLeaf"]
items += paragraphs("LICENSE")
items += ["", "#Code from others",
          "The inflate decoder follows puff by Mark Adler (zlib licence). The program is built with devkitARM and linked with libnds and libfat from devkitPro (devkitpro.org). Their licences follow the font notices below.",
          "", "#Fonts",
          "The menus use font8x8 by Daniel Hepper, public domain.", "",
          "The Built-in 6x12 font is a modified version of Terminus Font: Copyright (C) 2020 Dimitar Toshkov Zhekov, with Reserved Font Name \"Terminus Font\". "
          "It is licensed under the SIL Open Font License, Version 1.1, which follows.", "",
          "#SIL Open Font License"]
ofl = paragraphs("third_party/terminus/OFL.txt")
start = next(i for i, p in enumerate(ofl) if p.startswith("SIL OPEN FONT LICENSE"))
items += ofl[start:]
items += ["", "#Hyphenation patterns"] + paragraphs("third_party/hyphen/NOTICE.txt")
items += ["", "#libnds licence (zlib)"] + paragraphs("third_party/libnds/LICENSE.txt")
items += ["", "#libfat licence (BSD)"] + paragraphs("third_party/libfat/LICENSE.txt")

with open(os.path.join(root, "source/about_text.c"), "w", encoding="utf-8") as f:
    f.write("// Generated by tools/make_about.py from LICENSE and third_party/terminus/OFL.txt. Do not edit.\n")
    f.write("// A paragraph starting with '#' is a heading, an empty one is a blank line.\n")
    f.write('#include "about.h"\n#include "version.h"\n\nconst char *const about_paragraphs[] = {\n')
    for p in items:
        if "DSLEAF_VERSION" in p:        # the version is joined to the text by the compiler
            f.write('\t"#DSLeaf " DSLEAF_VERSION,\n')
            continue
        p = ascii_only(p).replace("\\", "\\\\").replace('"', '\\"')
        f.write('\t"%s",\n' % p)
    f.write("};\n\nconst int about_paragraph_count = %d;\n" % len(items))
