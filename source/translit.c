int translit_letter(uint32_t cp, uint8_t out[3]) {
	size_t lo = 0, hi = sizeof table / sizeof table[0];
	while (lo < hi) {
		size_t mid = (lo + hi) / 2;
		if (table[mid].cp < cp) lo = mid + 1;
		else hi = mid;
	}
	if (lo >= sizeof table / sizeof table[0] || table[lo].cp != cp) return 0;
	int n = (int)strlen(table[lo].text);
	memcpy(out, table[lo].text, (size_t)n);
	return n;
}
